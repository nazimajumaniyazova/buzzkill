import { SPRITES } from '@buzzkill/art';

import type { AssetPlan } from './plan';

/** The file names of the generated outputs, in `PATHS.output`. */
export const atlasFile = (name: string): string => `${name}.webp`;
export const wavFile = (id: string): string => `${id}.wav`;

/**
 * The TypeScript source of the asset manifest: the URL of every file the game loads, the size of
 * each atlas and the frames of each sprite, and in a comment the input hash of each output. The
 * output is stable, so the manifest test can compare it with the committed file.
 */
export function renderManifest(plan: AssetPlan): string {
  const lines: string[] = [
    '// Generated by `pnpm assets` (apps/web/scripts/assets, ADR-0016) from @buzzkill/art and',
    '// apps/web/assets-src/sounds. Do not edit: `scripts/assets/manifest.test.ts` fails when this',
    '// file no longer matches the art or the sounds.',
    '//',
    '// The input of each file, as SHA-256:',
    ...plan.atlases.map((atlas) => `//   ${atlasFile(atlas.name).padEnd(16)}${atlas.input}`),
    ...plan.sounds.map((sound) => `//   ${wavFile(sound.id).padEnd(16)}${sound.input}`),
    '',
    ...plan.atlases.map((atlas) => `import ${atlas.name}Atlas from './${atlasFile(atlas.name)}';`),
    ...plan.sounds.flatMap((sound) => [
      `import ${sound.id}Ogg from '../../assets-src/sounds/${sound.source}';`,
      `import ${sound.id}Wav from './${wavFile(sound.id)}';`,
    ]),
    '',
    '/** The atlases the game loads, with their size in pixels. */',
    'export const ATLASES = {',
    ...plan.atlases.map(
      (atlas) =>
        `  ${atlas.name}: { url: ${atlas.name}Atlas, width: ${String(atlas.width)}, height: ${String(atlas.height)} },`,
    ),
    '} as const;',
    '',
    '/**',
    ' * Every sprite the game draws: its atlas, the ticks each frame stays on screen and its frames in',
    " * atlas pixels. The art is drawn at twice the world's pixels.",
    ' */',
    'export const SPRITES = {',
  ];
  for (const atlas of plan.atlases) {
    const names = [...new Set(atlas.placements.map((placement) => placement.name))];
    for (const name of names) {
      lines.push(
        `  ${key(name)}: {`,
        `    atlas: '${atlas.name}',`,
        `    frameTicks: ${String(SPRITES[name].frameTicks)},`,
        '    frames: [',
      );
      for (const { x, y, width, height } of atlas.placements.filter((p) => p.name === name)) {
        lines.push(
          `      { x: ${String(x)}, y: ${String(y)}, width: ${String(width)}, height: ${String(height)} },`,
        );
      }
      lines.push('    ],', '  },');
    }
  }
  lines.push(
    '} as const;',
    '',
    '/** Every sound: the Ogg file as downloaded, and a WAV for browsers that cannot decode it. */',
    'export const SOUNDS = {',
    ...plan.sounds.map(
      (sound) => `  ${sound.id}: { url: ${sound.id}Ogg, fallbackUrl: ${sound.id}Wav },`,
    ),
    '} as const;',
    '',
  );
  return lines.join('\n');
}

/** An object key: bare when it is an identifier, quoted otherwise. */
function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`;
}
