// @vitest-environment node
// The stylesheet comparison reads a file next to this test, which needs `import.meta.url` to be
// a file URL; under jsdom it is not.
import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { DARK_THEME, declaration, DEFAULT_THEME, renderTokensCss } from './css';
import { collect, type TokenGroup } from './define';
import { tokens } from './tokens';

/** The lines of a top-level rule, between `selector {` and its closing brace. */
function topLevelBlock(css: string, selector: string): string[] {
  const opening = `\n${selector} {\n`;
  const start = css.indexOf(opening);
  expect(start).toBeGreaterThanOrEqual(0);
  const end = css.indexOf('\n}', start);
  return css.slice(start + opening.length, end).split('\n');
}

/** A rule nested one level deep, as the generator formats it inside a media query. */
function nested(selector: string, group: TokenGroup, extra: readonly string[] = []): string {
  return [
    `  ${selector} {`,
    ...collect(group).map((token) => declaration(token, 2)),
    ...(extra.length === 0 ? [] : ['', ...extra.map((line) => `    ${line}`)]),
    '  }',
  ].join('\n');
}

describe('renderTokensCss', () => {
  const css = renderTokensCss();
  const lines = css.split('\n');
  const { color } = tokens.semantic;
  const { contrastMore, reducedMotion } = tokens.preferences;

  it('starts with the generated-file notice and ends with a single newline', () => {
    expect(lines[0]).toMatch(/^\/\* Generated by .* Do not edit by hand\. \*\/$/);
    expect(lines[1]).toBe('');
    expect(css.endsWith('}\n')).toBe(true);
    expect(css.endsWith('\n\n')).toBe(false);
  });

  it('declares primitives with their values and the upper layers with var() references', () => {
    expect(declaration(tokens.primitives.palette.neutral[0])).toBe('  --palette-neutral-0: #fff;');
    expect(declaration(tokens.semantic.space.inset.md, 2)).toBe(
      '    --space-inset-md: var(--spacing-4);',
    );
    expect(css).toContain('  --palette-neutral-0: #fff;\n');
    expect(css).toContain('  --space-inset-md: var(--spacing-4);\n');
  });

  it('puts every layer, the default theme and its color scheme on :root', () => {
    const root = topLevelBlock(css, ':root');
    const expected = [
      ...collect(tokens.primitives),
      ...collect(tokens.semantic.space),
      ...collect(color[DEFAULT_THEME]),
    ].map((token) => declaration(token));

    for (const line of expected) {
      expect(root).toContain(line);
    }
    expect(root.indexOf(declaration(tokens.primitives.palette.neutral[0]))).toBeLessThan(
      root.indexOf(declaration(color[DEFAULT_THEME].surface)),
    );
    expect(root.at(-1)).toBe('  color-scheme: light;');
  });

  it('overrides the semantic colors and the color scheme per other theme', () => {
    expect(topLevelBlock(css, `[data-theme='${DARK_THEME}']`)).toEqual([
      ...collect(color[DARK_THEME]).map((token) => declaration(token)),
      '',
      '  color-scheme: dark;',
    ]);
    expect(css).not.toContain(`[data-theme='${DEFAULT_THEME}']`);
  });

  it('applies the dark theme to a dark system preference only while no theme is chosen', () => {
    expect(css).toContain(
      [
        '@media (prefers-color-scheme: dark) {',
        nested(':root:not([data-theme])', color[DARK_THEME], ['color-scheme: dark;']),
        '}',
      ].join('\n'),
    );
  });

  it('raises the contrast per theme under prefers-contrast: more', () => {
    expect(css).toContain(
      [
        '@media (prefers-contrast: more) {',
        nested(':root', contrastMore[DEFAULT_THEME]),
        '',
        nested(`[data-theme='${DARK_THEME}']`, contrastMore[DARK_THEME]),
        '}',
      ].join('\n'),
    );
    expect(css).toContain(
      [
        '@media (prefers-contrast: more) and (prefers-color-scheme: dark) {',
        nested(':root:not([data-theme])', contrastMore[DARK_THEME]),
        '}',
      ].join('\n'),
    );
  });

  it('zeroes the motion tokens under prefers-reduced-motion: reduce, unless the page asks for full motion', () => {
    expect(css).toContain(
      [
        '@media (prefers-reduced-motion: reduce) {',
        nested(":root:not([data-motion='full'])", reducedMotion),
        '}',
      ].join('\n'),
    );
  });

  it("zeroes the motion tokens under data-motion='reduced' whatever the system says", () => {
    expect(topLevelBlock(css, ":root[data-motion='reduced']")).toEqual(
      collect(reducedMotion).map((token) => declaration(token)),
    );
  });

  it('writes one declaration per line in the form Stylelint and Prettier keep', () => {
    const declarations = lines.filter((line) => line.endsWith(';'));

    expect(declarations.length).toBeGreaterThan(0);
    for (const line of declarations) {
      expect(line).toMatch(/^ {2}(?: {2})?(?:--[a-z0-9-]+|color-scheme): [^A-Z"]+;$/);
    }
  });

  it('matches the committed tokens.css; `pnpm --filter @buzzkill/ui tokens` regenerates it', () => {
    expect(readFileSync(new URL('./tokens.css', import.meta.url), 'utf8')).toBe(css);
  });
});
