/**
 * Bundles the submit-run function (#218) into one ES module for Supabase's Deno runtime:
 * `function/main.ts`, the backend logic, the game and zod. The game version is the one the web
 * app of the same commit plays (`gameVersion()`), so the server accepts that build's runs only.
 */
import { join } from 'node:path';

import { gameVersion } from '@buzzkill/config/game-version';
import { build } from 'esbuild';

const REPOSITORY = join(import.meta.dirname, '../../..');
const OUTPUT = join(REPOSITORY, 'supabase/functions/submit-run/index.js');

const version = gameVersion(REPOSITORY);

await build({
  entryPoints: [join(import.meta.dirname, '../function/main.ts')],
  outfile: OUTPUT,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2023',
  define: { __GAME_VERSION__: JSON.stringify(version) },
  banner: {
    js: `// Generated by \`pnpm functions:build\` from packages/server, game ${version}. Do not edit.`,
  },
  logLevel: 'warning',
});

process.stdout.write(`Bundled submit-run for game ${version} into ${OUTPUT}\n`);
